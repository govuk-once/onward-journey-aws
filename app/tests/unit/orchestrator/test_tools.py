# =====================================================================

@pytest.mark.asyncio
@patch("app.agentcore.orchestrator.tools.ClientSession")
@patch("app.agentcore.orchestrator.tools.aws_iam_streamablehttp_client")
async def test_tool_handles_mcp_gateway_error(mock_stream_client, mock_client_session):
    """
    Test that if the MCP SDK throws an unhandled exception (e.g. network timeout),
    the tool safely catches it and returns a string error to the LLM rather than crashing.
    """
    mock_session_instance = AsyncMock()
    mock_session_instance.call_tool.side_effect = Exception("Connection timed out")

    mock_client_session.return_value.__aenter__.return_value = mock_session_instance

    mock_stream_cm = AsyncMock()
    mock_stream_cm.__aenter__.return_value = (AsyncMock(), AsyncMock(), AsyncMock())
    mock_stream_client.return_value = mock_stream_cm

    # Dummy config since query_department_database doesn't explicitly read it
    result = await query_department_database.ainvoke({"query": "passports"}, config={"configurable": {}})

    assert result == "ERROR: Gateway call failed: Connection timed out"
