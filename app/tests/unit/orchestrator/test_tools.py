import pytest
import httpx
from unittest.mock import patch, AsyncMock, MagicMock

from app.agentcore.orchestrator.tools import (
    VPCETransport,
    query_department_database,
    crm_live_chat_tools
)

# =====================================================================
# 1. VPC TRANSPORT TESTS
# =====================================================================

@pytest.mark.asyncio
async def test_vpce_transport_rewrites_host_and_url():
    """
    Test that the custom transport overrides the physical URL host to hit the VPCE,
    but retains the Canonical Host in the headers for AWS SigV4 validation.
    """
    transport = VPCETransport(vpce_host="vpce.mock.aws", canonical_host="canonical.mock.aws")

    # Simulate outgoing request generated by MCP SDK
    request = httpx.Request("POST", "https://canonical.mock.aws/mcp")

    # Patch underlying httpx transport handler so it doesn't fire onto the network
    with patch("httpx.AsyncHTTPTransport.handle_async_request", new_callable=AsyncMock) as mock_super:
        mock_super.return_value = httpx.Response(200)
        await transport.handle_async_request(request)

    # Assert 1: Header was explicitly set to the canonical host
    assert request.headers.get("Host") == "canonical.mock.aws"

    # Assert 2: Actual routing URL was swapped to the VPCE host
    assert request.url.host == "vpce.mock.aws"


